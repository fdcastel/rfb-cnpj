-- csv_estabelecimento.sql
SELECT
    cnpj_base,
    cnpj_ordem,
    cnpj_dv,
    matriz = '1' AS matriz,
    nome_fantasia,
    situacao_cadastral,
    {{ rfb_date('data_situacao_cadastral') }} AS data_situacao_cadastral,
    motivo_situacao_cadastral,
    nome_cidade_exterior,
    pais,
    {{ rfb_date('data_inicio_atividades') }} AS data_inicio_atividades,
    cnae,
    cnae_secundario,
    tipo_logradouro,
    logradouro,
    CASE WHEN UPPER(TRIM(numero)) IN ('S/N', 'SN', 'S N', 'S/Nº', 'S/N.', '-', 'S/NR', '.', 'SNR', 'S.N', 'S-N', 'SEM', 'SEM NM', 'SEM NU', 'S\N', '0', '00', '000', '0000', '00000', '000000') THEN NULL ELSE numero END AS numero,
    complemento,
    bairro,
    LPAD(cep, 8, '0') AS cep,
    uf,
    municipio,
    ddd1,
    telefone1,
    ddd2,
    telefone2,
    ddd_fax,
    fax,
    LOWER(correio_eletronico) AS correio_eletronico,
    situacao_especial,
    {{ rfb_date('data_situacao_especial') }} AS data_situacao_especial,
    -- CNPJ parts are strings: alphanumeric CNPJs exist since 2026-07 (e.g. ordem 'E08G').
    substr(cnpj_base, 1, 2) || '.' || substr(cnpj_base, 3, 3) || '.' || substr(cnpj_base, 6, 3)
        || '/' || cnpj_ordem || '-' || cnpj_dv AS cnpj
FROM
    read_csv({{ csv_source('*.ESTABELE') }},
             header = false,
             columns = {'cnpj_base': 'VARCHAR',
                        'cnpj_ordem': 'VARCHAR',
                        'cnpj_dv': 'VARCHAR',
                        'matriz': 'VARCHAR',
                        'nome_fantasia': 'VARCHAR',
                        'situacao_cadastral': 'UTINYINT',
                        'data_situacao_cadastral': 'VARCHAR',
                        'motivo_situacao_cadastral': 'UTINYINT',
                        'nome_cidade_exterior': 'VARCHAR',
                        'pais': 'VARCHAR',
                        'data_inicio_atividades': 'VARCHAR',
                        'cnae': 'VARCHAR',
                        'cnae_secundario': 'VARCHAR',
                        'tipo_logradouro': 'VARCHAR',
                        'logradouro': 'VARCHAR',
                        'numero': 'VARCHAR',
                        'complemento': 'VARCHAR',
                        'bairro': 'VARCHAR',
                        'cep': 'VARCHAR',
                        'uf': 'VARCHAR',
                        'municipio': 'USMALLINT',
                        'ddd1': 'VARCHAR',
                        'telefone1': 'VARCHAR',
                        'ddd2': 'VARCHAR',
                        'telefone2': 'VARCHAR',
                        'ddd_fax': 'VARCHAR',
                        'fax': 'VARCHAR',
                        'correio_eletronico': 'VARCHAR',
                        'situacao_especial': 'VARCHAR',
                        'data_situacao_especial': 'VARCHAR'},
             quote = '"',
             escape = '"',
             nullstr = '',
             delim = ';')
